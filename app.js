let currentLanguage = "en";
let currentError = "";

function setLanguage(language) {
    currentLanguage = language;
    document.documentElement.lang = language;
    document.querySelectorAll("[data-i18n]").forEach((element) => {
        const translation = translations[language][element.dataset.i18n];
        if (translation !== undefined) {
            element.textContent = translation;
        }
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
        const translation = translations[language][element.dataset.i18nPlaceholder];
        if (translation !== undefined) {
            element.placeholder = translation;
        }
    });
    document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
        const translation = translations[language][element.dataset.i18nAria];
        if (translation !== undefined) {
            element.setAttribute("aria-label", translation);
        }
    });
    document.querySelectorAll("[data-language]").forEach((button) => {
        button.setAttribute("aria-pressed", String(button.dataset.language === language));
    });
    document.getElementById("doctorPhoto").alt = language === "hi"
        ? "डॉ. नीरज चतुर्वेदी की तस्वीर"
        : "Photo of Dr. Neeraj Chaturvedi";
    if (currentError) {
        formMessage.textContent = validationMessages[language][currentError];
    }
}

document.querySelectorAll("[data-language]").forEach((button) => {
    button.addEventListener("click", () => setLanguage(button.dataset.language));
});

