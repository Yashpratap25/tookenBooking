function getLocalDateString(date) {
    const year = date.getFullYear();
    const month = String(date.getMonth() + 1).padStart(2, "0");
    const day = String(date.getDate()).padStart(2, "0");
    return `${year}-${month}-${day}`;
}

function formatAppointmentDate(dateString) {
    return new Intl.DateTimeFormat(currentLanguage === "hi" ? "hi-IN" : "en-IN", {
        day: "numeric",
        month: "long",
        year: "numeric"
    }).format(new Date(`${dateString}T00:00:00`));
}

const today = getLocalDateString(new Date());
appointmentDateInput.min = today;
appointmentDateInput.value = today;

const dateQuickPickButtons = document.querySelectorAll("[data-date-offset]");

function getDateWithOffset(offset) {
    const date = new Date();
    date.setDate(date.getDate() + offset);
    return getLocalDateString(date);
}

function updateQuickDateSelection() {
    dateQuickPickButtons.forEach((button) => {
        button.setAttribute("aria-pressed", String(
            appointmentDateInput.value === getDateWithOffset(Number(button.dataset.dateOffset))
        ));
    });
}

dateQuickPickButtons.forEach((button) => {
    button.addEventListener("click", () => {
        appointmentDateInput.value = getDateWithOffset(Number(button.dataset.dateOffset));
        appointmentDateInput.dispatchEvent(new Event("change", { bubbles: true }));
    });
});
updateQuickDateSelection();

function setInvalid(input, invalid) {
    if (invalid) {
        input.setAttribute("aria-invalid", "true");
    } else {
        input.removeAttribute("aria-invalid");
    }
}

appointmentForm.addEventListener("submit", (event) => {
    event.preventDefault();
    formMessage.textContent = "";
    currentError = "";

    const name = patientNameInput.value.trim();
    const phone = patientPhoneInput.value.trim();
    const date = appointmentDateInput.value;
    const nameInvalid = name.length < 2;
    const phoneInvalid = !/^[6-9][0-9]{9}$/.test(phone);
    const dateInvalid = !date || date < getLocalDateString(new Date());
    const consentInvalid = !privacyConsentInput.checked;

    setInvalid(patientNameInput, nameInvalid);
    setInvalid(patientPhoneInput, phoneInvalid);
    setInvalid(appointmentDateInput, dateInvalid);

    if (nameInvalid || phoneInvalid || dateInvalid || consentInvalid) {
        currentError = consentInvalid
            ? "consent"
            : phoneInvalid
                ? "phone"
                : dateInvalid
                    ? "date"
                    : "name";
        formMessage.textContent = validationMessages[currentLanguage][currentError];
        const firstInvalid = nameInvalid
            ? patientNameInput
            : phoneInvalid
                ? patientPhoneInput
                : dateInvalid
                    ? appointmentDateInput
                    : privacyConsentInput;
        firstInvalid.focus();
        return;
    }

    const storageKey = `heartline-token-count-${date}`;
    let tokenNumber;

    try {
        const savedCount = localStorage.getItem(storageKey);
        const previousCount = savedCount === null ? 0 : Number(savedCount);
        if (!Number.isSafeInteger(previousCount) || previousCount < 0 || previousCount >= 999999) {
            throw new Error("The saved token counter is invalid.");
        }
        tokenNumber = previousCount + 1;
        localStorage.setItem(storageKey, String(tokenNumber));
    } catch (error) {
        currentError = "storage";
        formMessage.textContent = validationMessages[currentLanguage][currentError];
        console.error("Unable to create the local appointment token:", error);
        return;
    }

    const compactDate = date.replaceAll("-", "");
    tokenValue.textContent = `HL-${compactDate}-${String(tokenNumber).padStart(3, "0")}`;
    tokenPatient.textContent = name;
    tokenDate.textContent = formatAppointmentDate(date);
    appointmentForm.hidden = true;
    tokenResult.hidden = false;
    tokenResult.scrollIntoView({ behavior: "smooth", block: "nearest" });
});

patientNameInput.addEventListener("input", () => setInvalid(patientNameInput, false));
patientPhoneInput.addEventListener("input", () => setInvalid(patientPhoneInput, false));
appointmentDateInput.addEventListener("change", () => {
    setInvalid(appointmentDateInput, false);
    updateQuickDateSelection();
});
privacyConsentInput.addEventListener("change", () => {
    if (privacyConsentInput.checked) {
        currentError = "";
        formMessage.textContent = "";
    }
});

anotherBookingButton.addEventListener("click", () => {
    appointmentForm.reset();
    currentError = "";
    appointmentDateInput.value = getLocalDateString(new Date());
    appointmentDateInput.min = appointmentDateInput.value;
    updateQuickDateSelection();
    setInvalid(patientNameInput, false);
    setInvalid(patientPhoneInput, false);
    setInvalid(appointmentDateInput, false);
    formMessage.textContent = "";
    tokenResult.hidden = true;
    appointmentForm.hidden = false;
    patientNameInput.focus();
});

